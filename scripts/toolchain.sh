#!/bin/sh
# Set up the runner build toolchain in runners/toolchain/ (git-ignored).
# No sudo and nothing system-wide: delete runners/toolchain/ to remove it all.
# Prints nothing on success except progress; then `. runners/toolchain/env.sh`.
set -eu
cd "$(dirname "$0")/.."
ROOT=$(pwd)/toolchain
DL=$ROOT/downloads
mkdir -p "$DL"

# Pinned versions. Bump deliberately and update the checksum from the publisher.
LLVM_MINGW=20261006
LLVM_MINGW_SHA256=a7a19b11048e89372637d26279cdb7c430ed3cf8c1e224310421312bf986ebf6
BISON=3.8.2
BISON_SHA256=9bba0214ccf7f1079c5d59210045227bcf619519840ebfa80cd3849cff5a5bf2

fetch() { # <url> <sha256>
  file=$DL/$(basename "$1")
  if [ ! -f "$file" ]; then
    curl -fL --retry 3 "$1" -o "$file.part" >&2
    mv "$file.part" "$file"
  fi
  echo "$2  $file" | shasum -a 256 -c - >/dev/null || {
    echo "checksum mismatch for $file; delete it and retry" >&2
    exit 1
  }
  echo "$file"
}

# PE cross-compiler (clang + lld targeting Windows). Universal binary.
if [ ! -x "$ROOT/llvm-mingw/bin/x86_64-w64-mingw32-clang" ]; then
  echo "== llvm-mingw $LLVM_MINGW"
  archive=$(fetch "https://github.com/mstorsjo/llvm-mingw/releases/download/$LLVM_MINGW/llvm-mingw-$LLVM_MINGW-ucrt-macos-universal.tar.xz" "$LLVM_MINGW_SHA256")
  rm -rf "$ROOT/llvm-mingw" && mkdir -p "$ROOT/llvm-mingw"
  tar xJf "$archive" -C "$ROOT/llvm-mingw" --strip-components=1
  # Downloaded binaries carry the quarantine flag; this is our own build input.
  xattr -dr com.apple.quarantine "$ROOT/llvm-mingw" 2>/dev/null || true
fi

# Wine needs bison >= 3.0; macOS ships 2.3.
if [ ! -x "$ROOT/bison/bin/bison" ]; then
  echo "== bison $BISON"
  archive=$(fetch "https://mirrors.kernel.org/gnu/bison/bison-$BISON.tar.xz" "$BISON_SHA256")
  src=$ROOT/src/bison-$BISON
  rm -rf "$src" && mkdir -p "$src"
  tar xJf "$archive" -C "$src" --strip-components=1
  (cd "$src" && ./configure --quiet --prefix="$ROOT/bison" && make -s -j"$(sysctl -n hw.ncpu)" && make -s install)
fi

cat > "$ROOT/env.sh" <<ENV
# Generated by runners/scripts/toolchain.sh
# llvm-mingw goes last: it ships its own \`clang\`, which must not shadow Xcode's.
export PATH="$ROOT/bison/bin:\$PATH:$ROOT/llvm-mingw/bin"
ENV
echo "toolchain ready: . $ROOT/env.sh"
