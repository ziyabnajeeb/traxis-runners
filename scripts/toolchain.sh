#!/bin/sh
# Set up the runner build toolchain in runners/toolchain/ (git-ignored).
# No sudo and nothing system-wide: delete runners/toolchain/ to remove it all.
# Prints nothing on success except progress; then `. runners/toolchain/env.sh`.
set -eu
cd "$(dirname "$0")/.."
ROOT=$(pwd)/toolchain
DL=$ROOT/downloads
mkdir -p "$DL"

# Pinned versions. Bump deliberately and update the checksum from the publisher.
LLVM_MINGW=20261006
LLVM_MINGW_SHA256=a7a19b11048e89372637d26279cdb7c430ed3cf8c1e224310421312bf986ebf6
BISON=3.8.2
BISON_SHA256=9bba0214ccf7f1079c5d59210045227bcf619519840ebfa80cd3849cff5a5bf2
# For GStreamer (build-wine.sh deps): meson and ninja from PyPI (checksums as
# PyPI lists them); pkgconf and nasm publish none, so these are the files as
# first downloaded over HTTPS from their sites.
MESON=1.6.1
MESON_SHA256=3f41f6b03df56bb76836cc33c94e1a404c3584d48b3259540794a60a21fad1f9
NINJA=1.11.1.3
NINJA_SHA256=2b4879ea3f1169f3d855182c57dcc84d1b5048628c8b7be0d702b81882a37237
PKGCONF=2.3.0
PKGCONF_SHA256=3a9080ac51d03615e7c1910a0a2a8df08424892b5f13b0628a204d3fcce0ea8b
NASM=2.16.03
NASM_SHA256=1412a1c760bbd05db026b6c0d1657affd6631cd0a63cddb6f73cc6d4aa616148

fetch() { # <url> <sha256>
  file=$DL/$(basename "$1")
  if [ ! -f "$file" ]; then
    curl -fL --retry 3 "$1" -o "$file.part" >&2
    mv "$file.part" "$file"
  fi
  echo "$2  $file" | shasum -a 256 -c - >/dev/null || {
    echo "checksum mismatch for $file; delete it and retry" >&2
    exit 1
  }
  echo "$file"
}

# PE cross-compiler (clang + lld targeting Windows). Universal binary.
if [ ! -x "$ROOT/llvm-mingw/bin/x86_64-w64-mingw32-clang" ]; then
  echo "== llvm-mingw $LLVM_MINGW"
  archive=$(fetch "https://github.com/mstorsjo/llvm-mingw/releases/download/$LLVM_MINGW/llvm-mingw-$LLVM_MINGW-ucrt-macos-universal.tar.xz" "$LLVM_MINGW_SHA256")
  rm -rf "$ROOT/llvm-mingw" && mkdir -p "$ROOT/llvm-mingw"
  tar xJf "$archive" -C "$ROOT/llvm-mingw" --strip-components=1
  # Downloaded binaries carry the quarantine flag; this is our own build input.
  xattr -dr com.apple.quarantine "$ROOT/llvm-mingw" 2>/dev/null || true
fi

# Wine needs bison >= 3.0; macOS ships 2.3.
if [ ! -x "$ROOT/bison/bin/bison" ]; then
  echo "== bison $BISON"
  archive=$(fetch "https://mirrors.kernel.org/gnu/bison/bison-$BISON.tar.xz" "$BISON_SHA256")
  src=$ROOT/src/bison-$BISON
  rm -rf "$src" && mkdir -p "$src"
  tar xJf "$archive" -C "$src" --strip-components=1
  (cd "$src" && ./configure --quiet --prefix="$ROOT/bison" && make -s -j"$(sysctl -n hw.ncpu)" && make -s install)
fi

# meson and ninja build GLib and GStreamer, in their own virtualenv.
if [ ! -x "$ROOT/py/bin/meson" ]; then
  echo "== meson $MESON, ninja $NINJA"
  meson_whl=$(fetch "https://files.pythonhosted.org/packages/py3/m/meson/meson-$MESON-py3-none-any.whl" "$MESON_SHA256")
  ninja_whl=$(fetch "https://files.pythonhosted.org/packages/py3/n/ninja/ninja-$NINJA-py3-none-macosx_10_9_universal2.whl" "$NINJA_SHA256")
  rm -rf "$ROOT/py" && python3 -m venv "$ROOT/py"
  "$ROOT/py/bin/pip" install -q --no-index --no-deps "$meson_whl" "$ninja_whl"
fi

# pkg-config, so Wine's configure finds GStreamer; nasm for FFmpeg's SIMD code.
build_autotools_tool() { # <name> <version> <archive> <binary>
  if [ ! -x "$ROOT/tools/bin/$4" ]; then
    echo "== $1 $2"
    src=$ROOT/src/$1-$2
    rm -rf "$src" && mkdir -p "$src"
    tar xJf "$3" -C "$src" --strip-components=1
    (cd "$src" && ./configure --quiet --prefix="$ROOT/tools" && make -s -j"$(sysctl -n hw.ncpu)" && make -s install)
  fi
}
build_autotools_tool pkgconf "$PKGCONF" \
  "$(fetch "https://distfiles.ariadne.space/pkgconf/pkgconf-$PKGCONF.tar.xz" "$PKGCONF_SHA256")" pkgconf
ln -sf pkgconf "$ROOT/tools/bin/pkg-config"
build_autotools_tool nasm "$NASM" \
  "$(fetch "https://www.nasm.us/pub/nasm/releasebuilds/$NASM/nasm-$NASM.tar.xz" "$NASM_SHA256")" nasm

cat > "$ROOT/env.sh" <<ENV
# Generated by runners/scripts/toolchain.sh
# llvm-mingw goes last: it ships its own \`clang\`, which must not shadow Xcode's.
export PATH="$ROOT/bison/bin:$ROOT/tools/bin:$ROOT/py/bin:\$PATH:$ROOT/llvm-mingw/bin"
ENV
echo "toolchain ready: . $ROOT/env.sh"
